export const CAR_MAP: Record<CarId, CarSpec> = CARS.reduce(
  (acc, car) => {
    acc[car.id] = car;
    return acc;
  },
  {} as Record<CarId, CarSpec>,
);

const GARAGE_STORAGE_KEY = 'racing_car_1_garage_v1';

export function createDefaultGarage(): GarageProgress {
  return {
    coins: 500,
    ownedCars: ['apex-gt1', 'volt-x'],
    carHealth: {
      'apex-gt1': 100,
      'volt-x': 100,
    },
    wins: 0,
  };
}

export function loadGarageProgress(): GarageProgress {
  const def = createDefaultGarage();
  try {
    const raw = localStorage.getItem(GARAGE_STORAGE_KEY);
    if (!raw) return def;
    const parsed = JSON.parse(raw) as Partial<GarageProgress>;
    const owned = Array.isArray(parsed.ownedCars) && parsed.ownedCars.length > 0
      ? (parsed.ownedCars.filter((id) => Boolean(CAR_MAP[id as CarId])) as CarId[])
      : def.ownedCars;
    if (!owned.includes('apex-gt1')) owned.unshift('apex-gt1');
    return {
      coins: typeof parsed.coins === 'number' && parsed.coins >= 0 ? Math.round(parsed.coins) : def.coins,
      ownedCars: owned,
      carHealth: { ...def.carHealth, ...(parsed.carHealth || {}) },
      wins: typeof parsed.wins === 'number' ? parsed.wins : 0,
    };
  } catch {
    return def;
  }
}

export function saveGarageProgress(progress: GarageProgress): void {
  try {
    localStorage.setItem(GARAGE_STORAGE_KEY, JSON.stringify(progress));
  } catch {
    // ignore storage quota error
  }
}

export function getRepairCostForCar(carId: CarId, currentHealth: number): number {
  const spec = CAR_MAP[carId];
  if (!spec || currentHealth >= 100) return 0;
  const missingFraction = Math.max(0, 100 - currentHealth) / 100;
  return Math.max(5, Math.ceil(spec.repairCost * missingFraction));
}

export function getRaceRewardCoins(position: number, totalRacers: number, isMultiplayer: boolean): number {
  const baseByPos = position === 1 ? 250 : position === 2 ? 150 : position === 3 ? 95 : 55;
  const mpBonus = isMultiplayer ? 50 : 0;
  const fieldBonus = totalRacers > 4 ? 25 : 0;
  return baseByPos + mpBonus + fieldBonus;
}
